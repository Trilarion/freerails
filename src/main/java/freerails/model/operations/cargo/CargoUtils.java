package freerails.model.operations.cargo;

import freerails.model.ModelConstants;
import freerails.model.player.Player;
import freerails.model.operations.station.Station;
import freerails.model.operations.station.StationDemand;
import freerails.model.operations.station.StationUtils;
import freerails.model.operations.train.Train;
import freerails.model.operations.train.TrainUtils;
import freerails.model.operations.train.schedule.TrainOrder;
import freerails.model.operations.train.schedule.UnmodifiableSchedule;
import freerails.model.world.UnmodifiableWorld;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.EnumMap;
import java.util.List;
import java.util.Map;
import java.util.OptionalInt;

/** Utility methods for calculating and transferring cargo quantities. */
public class CargoUtils {

    /** Prevents instantiation of this utility class. */
    private CargoUtils() {
    }

    /**
     * Groups the complete wagon-loads in a bundle by cargo category. Each
     * returned list contains one cargo type identifier per complete carload;
     * partial loads are omitted.
     *
     * @param world world providing cargo definitions
     * @param cargoBatchBundle bundle whose loads are counted
     * @return lists of cargo identifiers, grouped by category
     */
    public static Map<CargoCategory, List<Integer>> calculateCarLoads(UnmodifiableWorld world, UnmodifiableCargoBatchBundle cargoBatchBundle) {
        Map<CargoCategory, List<Integer>> carLoadsByCategory = new EnumMap<>(CargoCategory.class);
        for (CargoCategory category : CargoCategory.values()) {
            carLoadsByCategory.put(category, new ArrayList<>());
        }

        for (Cargo cargo : world.getCargos()) {
            int cargoId = cargo.getId();
            int carLoads = cargoBatchBundle.getAmountOfType(cargoId)
                    / ModelConstants.UNITS_OF_CARGO_PER_WAGON;
            List<Integer> categoryCarLoads = carLoadsByCategory.get(cargo.getCategory());
            for (int i = 0; i < carLoads; i++) {
                categoryCarLoads.add(cargoId);
            }
        }
        return carLoadsByCategory;
    }

    /**
     * State generated by preparing a station stop cargo transfer.
     *
     * @param stationAfter cargo left waiting at the station after the stop
     * @param trainAfter cargo carried by the train after the stop
     * @param consist train wagons after any automatic consist update
     * @param cargoDroppedOff cargo dropped off because the station demanded it
     */
    public record CargoTransferPlan(CargoBatchBundle stationAfter, CargoBatchBundle trainAfter,
                                  List<Integer> consist, CargoBatchBundle cargoDroppedOff) {
    }

    /**
     * Prepares the full cargo state transition for a train stopping at a station.
     *
     * @param world world providing cargo, train, and terrain definitions
     * @param train train arriving at the station
     * @param station station being serviced
     * @param autoConsist whether the train's consist may be updated automatically
     * @return the prepared cargo state after the stop
     */
    public static CargoTransferPlan prepareCargoTransfer(UnmodifiableWorld world, Player player, Train train,
                                                        Station station, boolean autoConsist) {
        CargoBatchBundle trainAfter = new CargoBatchBundle(train.getCargoBatchBundle());
        CargoBatchBundle stationAfter = new CargoBatchBundle(station.getCargoBatchBundle());
        List<Integer> consist = new ArrayList<>(train.getConsist());
        CargoBatchBundle cargoDroppedOff = new CargoBatchBundle();

        for (CargoBatch cargoBatch : trainAfter.getCargoBatches()) {
            int cargoTypeId = cargoBatch.getCargoTypeId();
            StationDemand stationDemand = station.getDemandForCargo();

            if (stationDemand.isCargoDemanded(cargoTypeId) && station.getId() != cargoBatch.getOriginalStationId()) {
                int amount = trainAfter.getAmount(cargoBatch);
                cargoDroppedOff.addCargo(cargoBatch, amount);

                OptionalInt productCargoId = StationUtils.cargoConversionAtStation(world, station, cargoTypeId);
                if (productCargoId.isPresent()) {
                    int newCargoType = productCargoId.getAsInt();
                    CargoBatch newCargoBatch = new CargoBatch(
                            newCargoType, station.getLocation(), world.getClock().getCurrentTime(), station.getId());
                    stationAfter.addCargo(newCargoBatch, amount);
                }

                trainAfter.setAmount(cargoBatch, 0);
            }
        }

        List<Integer> spaceAvailable1 = TrainUtils.spaceAvailable2(world, train.getCargoBatchBundle(), train.getConsist());
        for (int cargoType1 = 0; cargoType1 < spaceAvailable1.size(); cargoType1++) {
            int quantity1 = spaceAvailable1.get(cargoType1);
            if (quantity1 < 0) {
                int amountToTransfer1 = -quantity1;
                int cargoId = world.getCargoAtIndex(cargoType1).getId();
                CargoUtils.transferCargo(cargoId, amountToTransfer1, trainAfter, stationAfter);
            }
        }

        if (autoConsist) {
            UnmodifiableSchedule schedule = train.getSchedule();
            int currentOrderIndex = schedule.getCurrentOrderIndex();
            if (currentOrderIndex >= 0) {
                List<WagonLoad> wagonsAvailable = new ArrayList<>();
                TrainOrder order = schedule.getOrder(currentOrderIndex);
                Station otherStation = world.getStation(player, order.getStationId());
                StationDemand demand = otherStation.getDemandForCargo();

                for (Cargo cargo : world.getCargos()) {
                    int cargoId = cargo.getId();
                    if (demand.isCargoDemanded(cargoId)) {
                        int amount = stationAfter.getAmountOfType(cargoId);

                        while (amount > 0) {
                            int amount2remove = Math.min(amount, ModelConstants.UNITS_OF_CARGO_PER_WAGON);
                            amount -= amount2remove;

                            if (amount2remove * 2 > ModelConstants.UNITS_OF_CARGO_PER_WAGON) {
                                wagonsAvailable.add(new WagonLoad(amount2remove, cargoId));
                            }
                        }
                    }
                }

                wagonsAvailable.sort(Comparator.comparingInt(WagonLoad::quantity).reversed());
                int numWagonsToadd = Math.min(wagonsAvailable.size(), 3);

                Integer[] temp = new Integer[numWagonsToadd];
                for (int i = 0; i < numWagonsToadd; i++) {
                    WagonLoad wagonload = wagonsAvailable.get(i);
                    temp[i] = wagonload.cargoType();
                }
                consist = new ArrayList<>(Arrays.asList(temp));
            }
        }

        List<Integer> spaceAvailable = TrainUtils.spaceAvailable2(world, trainAfter, consist);
        for (int cargoType = 0; cargoType < spaceAvailable.size(); cargoType++) {
            int quantity = spaceAvailable.get(cargoType);
            int cargoId = world.getCargoAtIndex(cargoType).getId();
            int amountToTransfer = Math.min(quantity, stationAfter.getAmountOfType(cargoId));
            CargoUtils.transferCargo(cargoId, amountToTransfer, stationAfter, trainAfter);
        }

        return new CargoTransferPlan(stationAfter, trainAfter, consist, cargoDroppedOff);
    }

    /**
     * Moves up to the requested amount of a cargo type between mutable bundles,
     * preserving the source batches.
     *
     * @param cargoTypeToTransfer cargo type identifier to move
     * @param amountToTransfer maximum quantity to move
     * @param from source bundle to remove cargo from
     * @param to destination bundle to receive cargo
     */
    public static void transferCargo(int cargoTypeToTransfer, int amountToTransfer, CargoBatchBundle from, CargoBatchBundle to) {
        if (0 == amountToTransfer) {
            return;
        }
        int amountTransferredSoFar = 0;

        for (CargoBatch cb: from.getCargoBatches()) {
            if (amountTransferredSoFar > amountToTransfer) {
                break;
            }

            if (cb.getCargoTypeId() == cargoTypeToTransfer) {
                int amount = from.getAmount(cb);
                int amountOfThisBatchToTransfer;

                if (amount < amountToTransfer - amountTransferredSoFar) {
                    amountOfThisBatchToTransfer = amount;
                    from.setAmount(cb, 0);
                } else {
                    amountOfThisBatchToTransfer = amountToTransfer - amountTransferredSoFar;
                    from.addCargo(cb, -amountOfThisBatchToTransfer);
                }

                to.addCargo(cb, amountOfThisBatchToTransfer);
                amountTransferredSoFar += amountOfThisBatchToTransfer;
            }
        }
    }
}
