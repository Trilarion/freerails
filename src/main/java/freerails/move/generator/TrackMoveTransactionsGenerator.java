package freerails.move.generator;

import freerails.model.ModelConstants;
import freerails.model.economy.Money;
import freerails.model.economy.transaction.ItemTransaction;
import freerails.model.economy.transaction.Transaction;
import freerails.model.economy.transaction.TransactionCategory;
import freerails.model.player.Player;
import freerails.model.simulation.Time;
import freerails.model.terrain.Terrain;
import freerails.model.track.TrackCategory;
import freerails.model.track.TrackPiece;
import freerails.model.track.TrackType;
import freerails.model.world.UnmodifiableWorld;
import freerails.move.AddTransactionMove;
import freerails.move.CompositeMove;
import freerails.move.Move;
import freerails.move.mapupdatemove.ChangeTrackPieceMove;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * Adds the transactions of a track move: the track bookkeeping and what the
 * acting player pays or is refunded. The track moves are generated by a client
 * or the server; the transactions are always calculated from the world that
 * generates them.
 *
 * <p><b>Track bookkeeping.</b> For every player and track type, the {@code TRACK}
 * item-transaction quantities add up to the length of that track type on the tiles
 * the player owns. Yearly maintenance, the balance-sheet track value, and
 * {@link freerails.model.economy.TransactionUtils#hasAnyTrackBeenBuilt} rely on
 * this. Quantity changes are therefore booked on the owner of each tile's track, as
 * zero-amount transactions, also when another player makes the change; a change of
 * track type moves the length from the old type to the new one.
 *
 * <p><b>Prices</b>, all charged to or refunded to the acting player:
 * <ul>
 *     <li>Added length: the track type's purchasing price per
 *     {@link ModelConstants#LENGTH_OF_STRAIGHT_TRACK_PIECE}, plus the terrain's track
 *     construction cost.</li>
 *     <li>Removed length: half the track type's purchasing price.</li>
 *     <li>A change of track type (upgrade, station, bridge): the difference in
 *     purchasing price for the length, if the new type costs more; there is no refund
 *     if it costs less. Changing into a station or bridge type additionally costs a
 *     fixed charge of the new type's yearly maintenance.</li>
 * </ul>
 * All charges are cash-constrained: the move fails if the player cannot pay them.
 */
public class TrackMoveTransactionsGenerator {

    private final Player player;
    private final UnmodifiableWorld world;
    /** Length changes, by owner player ID and track type ID. */
    private final Map<Integer, Map<Integer, Integer>> lengthChanges = new TreeMap<>();
    /** Added length to pay for, by track type ID. */
    private final Map<Integer, Integer> lengthAdded = new TreeMap<>();
    /** Removed length to refund, by track type ID. */
    private final Map<Integer, Integer> lengthRemoved = new TreeMap<>();
    /** Price differences of type changes, multiplied by the length. */
    private long typeChangeCostByLength;
    private long trackConstructionCostByLength;
    private long fixedCostsStations;
    private long fixedCostsBridges;

    /**
     * @param world the world the transactions are calculated from
     * @param player the Player on behalf of which this object generates
     *          transaction for
     */
    public TrackMoveTransactionsGenerator(UnmodifiableWorld world, Player player) {
        this.world = world;
        this.player = player;
    }

    /**
     * @param move the move to apply or process
     * @return a composite move containing the track move and its associated transactions
     */
    public CompositeMove addTransactions(Move move) {
        lengthChanges.clear();
        lengthAdded.clear();
        lengthRemoved.clear();
        typeChangeCostByLength = 0;
        trackConstructionCostByLength = 0;
        fixedCostsStations = 0;
        fixedCostsBridges = 0;
        unpackMove(move);

        Time time = world.getClock().getCurrentTime();
        List<Move> moves = new ArrayList<>();
        moves.add(move);

        // Track bookkeeping on the owners.
        for (Map.Entry<Integer, Map<Integer, Integer>> owner : lengthChanges.entrySet()) {
            Player ownerPlayer = playerWithId(owner.getKey());
            if (ownerPlayer == null) {
                // Track that belongs to no player of this world has no account.
                continue;
            }
            for (Map.Entry<Integer, Integer> change : owner.getValue().entrySet()) {
                if (change.getValue() != 0) {
                    Transaction quantity = new ItemTransaction(
                            TransactionCategory.TRACK, Money.ZERO, time, change.getValue(), change.getKey());
                    moves.add(new AddTransactionMove(ownerPlayer, quantity));
                }
            }
        }

        // What the acting player pays or is refunded.
        for (Map.Entry<Integer, Integer> added : lengthAdded.entrySet()) {
            Money price = world.getTrackType(added.getKey()).getPurchasingPrice();
            Money total = Money.opposite(
                    Money.divide(new Money(Math.multiplyExact(price.amount(), added.getValue())),
                            ModelConstants.LENGTH_OF_STRAIGHT_TRACK_PIECE));
            charge(moves, new ItemTransaction(TransactionCategory.TRACK, total, time, 0, added.getKey()));
        }
        for (Map.Entry<Integer, Integer> removed : lengthRemoved.entrySet()) {
            Money price = world.getTrackType(removed.getKey()).getPurchasingPrice();
            Money total = Money.divide(new Money(Math.multiplyExact(price.amount(), removed.getValue())),
                    ModelConstants.LENGTH_OF_STRAIGHT_TRACK_PIECE);
            // You only get half the money back.
            total = Money.divide(total, 2);
            charge(moves, new ItemTransaction(TransactionCategory.TRACK, total, time, 0, removed.getKey()));
        }
        long typeChangeCost = typeChangeCostByLength / ModelConstants.LENGTH_OF_STRAIGHT_TRACK_PIECE;
        if (typeChangeCost != 0) {
            charge(moves, new Transaction(TransactionCategory.TRACK, new Money(-typeChangeCost), time));
        }
        long trackConstructionCost = trackConstructionCostByLength / ModelConstants.LENGTH_OF_STRAIGHT_TRACK_PIECE;
        if (trackConstructionCost != 0) {
            charge(moves, new Transaction(TransactionCategory.TRACK, new Money(-trackConstructionCost), time));
        }
        if (fixedCostsStations != 0) {
            charge(moves, new Transaction(TransactionCategory.STATIONS, new Money(fixedCostsStations), time));
        }
        if (fixedCostsBridges != 0) {
            charge(moves, new Transaction(TransactionCategory.BRIDGES, new Money(fixedCostsBridges), time));
        }

        return new CompositeMove(moves);
    }

    private void charge(List<Move> moves, Transaction transaction) {
        moves.add(new AddTransactionMove(player, transaction, true));
    }

    /**
     * Collects the bookkeeping and prices of the track changes in a move,
     * including those nested in composite moves.
     *
     * @param move the move
     */
    private void unpackMove(Move move) {
        if (move instanceof ChangeTrackPieceMove trackPieceMove) {
            unpackTrackChange(trackPieceMove);
        } else if (move instanceof CompositeMove cm) {
            // Composite moves may contain other composite moves, so walk the nested structure recursively.
            for (Move component : cm.getMoves()) {
                unpackMove(component);
            }
        }
    }

    /**
     * Collects the bookkeeping and prices of one tile's track change.
     *
     * @param move the track change
     */
    private void unpackTrackChange(ChangeTrackPieceMove move) {
        TrackPiece before = move.getOldTrackPiece();
        TrackPiece after = move.getNewTrackPiece();
        // Track ownership never changes, so either piece names the owner.
        int owner = before != null ? before.playerId() : after.playerId();
        int oldLength = before != null ? before.trackConfiguration().getLength() : 0;
        int newLength = after != null ? after.trackConfiguration().getLength() : 0;

        if (before != null) {
            changeLength(owner, before.trackType(), -oldLength);
        }
        if (after != null) {
            changeLength(owner, after.trackType(), newLength);
        }

        if (before == null || after == null || before.trackType().equals(after.trackType())) {
            // Built, removed, or lengthened or shortened track of one type.
            TrackType trackType = before != null ? before.trackType() : after.trackType();
            if (newLength > oldLength) {
                lengthAdded.merge(trackType.getId(), newLength - oldLength, Integer::sum);
                addTerrainTrackCost(move, newLength - oldLength);
            } else if (oldLength > newLength) {
                lengthRemoved.merge(trackType.getId(), oldLength - newLength, Integer::sum);
            }
            return;
        }

        // A change of track type: pay the price difference for the length that stays.
        TrackType oldType = before.trackType();
        TrackType newType = after.trackType();
        int keptLength = Math.min(oldLength, newLength);
        long priceDifference = newType.getPurchasingPrice().amount() - oldType.getPurchasingPrice().amount();
        if (priceDifference > 0) {
            typeChangeCostByLength = Math.addExact(typeChangeCostByLength, Math.multiplyExact(priceDifference, keptLength));
        }
        if (newLength > oldLength) {
            lengthAdded.merge(newType.getId(), newLength - oldLength, Integer::sum);
            addTerrainTrackCost(move, newLength - oldLength);
        } else if (oldLength > newLength) {
            lengthRemoved.merge(oldType.getId(), oldLength - newLength, Integer::sum);
        }

        TrackCategory category = newType.getCategory();
        if (category == TrackCategory.STATION) {
            fixedCostsStations = Math.subtractExact(fixedCostsStations, newType.getYearlyMaintenance().amount());
        } else if (category == TrackCategory.BRIDGE) {
            fixedCostsBridges = Math.subtractExact(fixedCostsBridges, newType.getYearlyMaintenance().amount());
        }
    }

    private void changeLength(int owner, TrackType trackType, int length) {
        lengthChanges.computeIfAbsent(owner, id -> new TreeMap<>()).merge(trackType.getId(), length, Integer::sum);
    }

    private Player playerWithId(int playerId) {
        for (Player candidate : world.getPlayers()) {
            if (candidate.getId() == playerId) {
                return candidate;
            }
        }
        return null;
    }

    /**
     * Adds the add terrain track cost to this track move transactions generator.
     *
     * @param move the move
     * @param addedLength the added length
     */
    private void addTerrainTrackCost(ChangeTrackPieceMove move, int addedLength) {
        Terrain terrain = world.getTerrain(world.getTile(move.location()).terrainTypeId());
        long weightedCost = Math.multiplyExact(
                terrain.getTrackConstructionCostPerMile().amount(), addedLength);
        trackConstructionCostByLength = Math.addExact(trackConstructionCostByLength, weightedCost);
    }
}
